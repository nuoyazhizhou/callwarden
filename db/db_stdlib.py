    def import_stdlib_symbols(self) -> int:
        """导入 Python 标准库符号到数据库

        Returns:
            导入的符号数量
        """
        cur = self.conn.execute(
            "SELECT COUNT(*) as cnt FROM package_versions WHERE package_name = ? AND package_version = ?",
            ('stdlib', sys.version.split()[0])
        )
        row = cur.fetchone()
        if row and row['cnt'] > 0:
            return 0

        created = 0
        skipped = 0

        stdlib_modules = [
            'os', 'os.path', 'sys', 'json', 're', 'time', 'datetime',
            'collections', 'collections.abc', 'itertools', 'functools',
            'pathlib', 'shutil', 'subprocess', 'sqlite3', 'threading',
            'concurrent.futures', 'logging', 'argparse', 'warnings',
            'contextlib', 'dataclasses', 'typing', 'types', 'inspect',
            'hashlib', 'base64', 'io', 'tempfile', 'glob', 'fnmatch',
            'math', 'random', 'statistics', 'operator', 'copy', 'pickle',
            'weakref', 'gc', 'traceback', 'errno', 'signal', 'socket',
            'http', 'urllib', 'email', 'csv', 'configparser', 'xml',
            'html', 'string', 'unicodedata', 'codecs', 'locale', 'ast',
            'tokenize', 'py_compile', 'importlib', 'enum', 'numbers',
            'decimal', 'fractions', 'struct', 'ctypes', 'abc', 'pathlib',
        ]

        for mod_name in stdlib_modules:
            try:
                module = __import__(mod_name, fromlist=[''])
                count = self._import_module_symbols(mod_name, module)
                created += count
            except (ImportError, Exception):
                skipped += 1

        self.conn.execute(
            "INSERT OR IGNORE INTO package_versions (package_name, package_version) VALUES (?, ?)",
            ('stdlib', sys.version.split()[0])
        )
        self.conn.commit()
        print(t("cli.messages.stdlib_import_done", created=created, skipped=skipped))
        return created

    def _import_module_symbols(self, module_name: str, module) -> int:
        """导入单个模块的符号

        Args:
            module_name: 模块完整名称（如 'os.path'）
            module: 已导入的模块对象

        Returns:
            导入的符号数量
        """
        created = 0
        module_path = module.__file__ if hasattr(module, '__file__') else ''

        # 遍历模块的所有属性
        for name, obj in inspect.getmembers(module):
            if name.startswith('_'):
                continue

            kind = self._infer_symbol_kind(obj)
            if kind is None:
                continue

            signature = self._get_symbol_signature(obj, name)
            docstring = inspect.getdoc(obj) or ''

            # 构建 qualified_name
            qualified_name = f"{module_name}.{name}"

            # 检查是否已存在
            cur = self.conn.execute(
                "SELECT id FROM external_symbols WHERE qualified_name = ?",
                (qualified_name,)
            )
            if cur.fetchone():
                continue

            self.conn.execute(
                """INSERT INTO external_symbols
                   (package_name, package_version, module_path, qualified_name,
                    symbol_name, symbol_kind, signature, docstring, source_file)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                (
                    'stdlib',
                    sys.version.split()[0],
                    module_name,
                    qualified_name,
                    name,
                    kind,
                    signature,
                    docstring[:500] if docstring else '',
                    module_path,
                )
            )
            created += 1

        return created

    def _infer_symbol_kind(self, obj) -> Optional[str]:
        """推断符号类型

        Args:
            obj: Python 对象

        Returns:
            符号类型（fn/class/property/constant），无法推断返回 None
        """
        if inspect.isfunction(obj) or inspect.ismethod(obj):
            return 'fn'
        elif inspect.isclass(obj):
            return 'class'
        elif isinstance(obj, property):
            return 'property'
        elif isinstance(obj, (int, float, str, bool)):
            return 'constant'
        elif inspect.ismodule(obj):
            return 'module'
        else:
            return None

    def _get_symbol_signature(self, obj, name: str) -> str:
        """获取符号签名

        Args:
            obj: Python 对象
            name: 符号名称

        Returns:
            签名字符串（如 'def fn_name(arg1, arg2)'）
        """
        try:
            if inspect.isfunction(obj) or inspect.ismethod(obj):
                sig = inspect.signature(obj)
                params = str(sig)
                return f"def {name}{params}"
            elif inspect.isclass(obj):
                return f"class {name}"
            elif isinstance(obj, property):
                return f"@property {name}"
            elif isinstance(obj, (int, float, str, bool)):
                return f"{name} = {repr(obj)[:50]}"
        except (ValueError, TypeError):
            pass

        return name

    def get_stdlib_symbol(self, qualified_name: str) -> Optional[Dict[str, Any]]:
        """查询标准库符号

        Args:
            qualified_name: 符号限定名（如 'os.path.join'）

        Returns:
            符号信息字典，未找到返回 None
        """
        cur = self.conn.execute(
            "SELECT * FROM external_symbols WHERE qualified_name = ?",
            (qualified_name,)
        )
        row = cur.fetchone()
        return dict(row) if row else None

    def search_stdlib_symbols(self, name: str) -> List[Dict[str, Any]]:
        """搜索标准库符号

        Args:
            name: 符号名称或部分名称

        Returns:
            匹配的符号列表
        """
        cur = self.conn.execute(
            "SELECT * FROM external_symbols WHERE symbol_name LIKE ?",
            (f"%{name}%",)
        )
        return [dict(row) for row in cur.fetchall()]

    def has_stdlib_symbol(self, qualified_name: str) -> bool:
        """检查标准库符号是否存在

        Args:
            qualified_name: 符号限定名

        Returns:
            True 表示存在，False 表示不存在
        """
        cur = self.conn.execute(
            "SELECT COUNT(*) as cnt FROM external_symbols WHERE qualified_name = ?",
            (qualified_name,)
        )
        return cur.fetchone()['cnt'] > 0

