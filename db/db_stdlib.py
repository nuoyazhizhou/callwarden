    def import_stdlib_symbols_for_lang(self, lang: str) -> int:
        """导入指定语言的标准库符号

        Args:
            lang: 语言标识（rust/java/go/c/cpp/csharp/typescript/kotlin/ruby/swift/scala/elixir）

        Returns:
            导入的符号数量
        """
        if lang == "python":
            return self.import_stdlib_symbols()

        symbols = self.STDLIB_SYMBOLS.get(lang, [])
        if not symbols:
            return 0

        # 检查是否已导入
        pkg_name = f"stdlib-{lang}"
        cur = self.conn.execute(
            "SELECT COUNT(*) as cnt FROM package_versions WHERE package_name = ?",
            (pkg_name,)
        )
        if cur.fetchone()['cnt'] > 0:
            return 0

        created = 0
        for module_path, symbol_name, kind, signature in symbols:
            qualified_name = f"{module_path}.{symbol_name}" if module_path else symbol_name

            cur = self.conn.execute(
                "SELECT id FROM external_symbols WHERE qualified_name = ?",
                (qualified_name,)
            )
            if cur.fetchone():
                continue

            self.conn.execute(
                """INSERT INTO external_symbols
                   (package_name, package_version, module_path, qualified_name,
                    symbol_name, symbol_kind, signature, docstring, source_file)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                (
                    pkg_name,
                    '1.0',
                    module_path,
                    qualified_name,
                    symbol_name,
                    kind,
                    signature,
                    '',
                    '',
                )
            )
            created += 1

        self.conn.execute(
            "INSERT OR IGNORE INTO package_versions (package_name, package_version) VALUES (?, ?)",
            (pkg_name, '1.0')
        )
        self.conn.commit()
        return created

    def import_all_stdlib_symbols(self, languages: Optional[List[str]] = None) -> int:
        """导入所有支持语言的标准库符号

        Args:
            languages: 指定语言列表，为空则导入所有支持语言的标准库。
                       P20: build_full_graph 会传入项目实际检测到的语言集合，
                       避免给 Python 项目导入 Java/C/Rust 等无关 stdlib。

        Returns:
            总导入符号数量
        """
        if languages is None:
            languages = ['python'] + list(self.STDLIB_SYMBOLS.keys())

        total = 0
        for lang in languages:
            count = self.import_stdlib_symbols_for_lang(lang)
            total += count
            if count > 0:
                print(t(
                    "cli.messages.stdlib_import_lang_summary",
                    lang=lang,
                    count=count,
                    default=f"  {lang}: {count} symbols",
                ))

        return total