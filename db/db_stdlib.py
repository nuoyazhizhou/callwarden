"""
db_stdlib.py
============

标准库符号表模块：管理 Python 标准库的符号信息，
支持从标准库中提取函数、类、常量等符号，用于跨文件调用解析。

设计思路：
1. 使用 Python 的 inspect 模块遍历标准库模块
2. 将提取的符号存储到 external_symbols 表
3. 构建时自动导入标准库符号
4. 调用解析时优先查找项目内符号，再查找标准库符号
"""

